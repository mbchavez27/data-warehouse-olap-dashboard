// Regenerates src/api/contracts.js from the running API.
//
// Mock mode is the dashboard default, and its sample rows have to carry
// exactly the columns each SQL file returns. This writes the list that
// src/api/mock.js validates its rows against, so that promise stays checkable
// instead of resting on whoever edited a builder last.
//
//   node scripts/sync-contracts.mjs [--base http://localhost:8080]
//
// Needs the API running against a loaded warehouse. Run
// `npm run check:contracts` afterwards to diff the committed file against the
// live responses (that is the check CI cannot run: the source archive is not
// in the repository, so CI cannot build the warehouse).
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const args = process.argv.slice(2)
const base =
  (args.includes('--base') ? args[args.indexOf('--base') + 1] : null) ??
  process.env.API_BASE ??
  'http://localhost:8080'

const response = await fetch(`${base}/api/reports`)
if (!response.ok) throw new Error(`GET ${base}/api/reports answered ${response.status}`)
const body = await response.json()
const reports = body.reports ?? body

// Keyed by every path the dashboard can request, aliases included: it asks for
// r2/cube, which the API serves as courier_vehicle_cube.
const contract = {}
for (const report of reports) {
  for (const level of report.levels ?? []) {
    const columns = (level.columns ?? []).map((column) => (typeof column === 'string' ? column : column.name))
    for (const id of [level.id, ...(level.aliases ?? [])]) contract[`${report.id}/${id}`] = columns
  }
}

const levels = Object.keys(contract)
  .sort()
  .map((key) => `  '${key}': [\n${contract[key].map((column) => `    '${column}',`).join('\n')}\n  ],`)
  .join('\n')

const file = `// Generated by scripts/sync-contracts.mjs from GET /api/reports. Do not edit.
//
// The columns each report level returns, keyed by the path the dashboard asks
// for. src/api/mock.js validates its sample rows against this, so a mock
// builder that drifts from the SQL fails loudly instead of rendering a blank
// cell. Regenerate after an intentional query change:
//
//   npm run sync:contracts
export const CONTRACTS = {
${levels}
}

// The columns of one level, or an empty list for a path the mock does not serve.
export const columnsFor = (report, level) => CONTRACTS[\`\${report}/\${level}\`] ?? []
`

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'src', 'api', 'contracts.js')
await writeFile(target, file)
console.log(
  `${Object.keys(contract).length} levels and ${Object.values(contract).flat().length} columns written to ${path.relative(process.cwd(), target)}`,
)
